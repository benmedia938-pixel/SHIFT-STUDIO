// Helper to look up a tool by exact SEO url or id
export function getToolByUrl(url: string): ToolItem | undefined {
  const clean = url.endsWith('/') ? url : url + '/';
  return RAW_TOOLS_DATA.find(t => t.seoUrl === clean || t.seoUrl === url);
}

export function getToolById(id: string): ToolItem | undefined {
  return RAW_TOOLS_DATA.find(t => t.id === id);
}

export function getToolsByCluster(clusterSlug: string): ToolItem[] {
  return RAW_TOOLS_DATA.filter(t => t.clusterSlug === clusterSlug);
}
